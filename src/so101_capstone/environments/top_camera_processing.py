"""Process raw fixed-camera RGB frames for policy observations.

Gazebo supplies a high-resolution, undistorted pinhole image. This module can
apply configurable Brown-Conrady lens distortion and then resize the result to
the policy input resolution.

OpenCV is loaded lazily so importing the rest of the environment package does
not require OpenCV immediately.
"""

from __future__ import annotations

from dataclasses import dataclass
import math
from typing import Any

import numpy as np


def _load_cv2() -> Any:
    """Import OpenCV and provide a useful error on ABI incompatibility."""

    try:
        import cv2
    except (AttributeError, ImportError) as error:
        raise RuntimeError(
            "OpenCV could not be imported. Run the ROS environment with "
            "PYTHONNOUSERSITE=1 so the system NumPy and OpenCV packages "
            "use compatible binary interfaces."
        ) from error

    return cv2


def _positive_integer(
    value: int,
    *,
    name: str,
) -> int:
    if (
        isinstance(value, bool)
        or not isinstance(value, int)
        or value <= 0
    ):
        raise ValueError(f"{name} must be a positive integer.")

    return value


def _finite_float(
    value: float,
    *,
    name: str,
) -> float:
    result = float(value)

    if not math.isfinite(result):
        raise ValueError(f"{name} must be finite.")

    return result


@dataclass(frozen=True)
class TopCameraProcessingConfig:
    """Geometry and distortion configuration for the fixed camera."""

    input_height: int = 600
    input_width: int = 800
    output_height: int = 480
    output_width: int = 640

    horizontal_fov_rad: float = math.radians(100.0)

    k1: float = 0.0
    k2: float = 0.0
    p1: float = 0.0
    p2: float = 0.0
    k3: float = 0.0

    principal_x_fraction: float = 0.5
    principal_y_fraction: float = 0.5

    # Values above 1.0 zoom the distorted image inward and can reduce
    # invalid borders caused by strong barrel distortion.
    distorted_focal_scale: float = 1.0

    # Automatically crop the largest valid 4:3 rectangle after remapping.
    # This removes every border pixel generated by OpenCV BORDER_CONSTANT.
    crop_to_valid_region: bool = True

    # Require remap coordinates to remain this many source pixels inside
    # the source-image boundary. One pixel protects bilinear interpolation.
    valid_source_margin_px: float = 1.0

    # Optional deterministic crop applied after distortion remapping.
    # Coordinates are x0, y0, x1, y1 in the distorted 800x600 image.
    fixed_crop_xyxy: (
        tuple[int, int, int, int] | None
    ) = None

    def __post_init__(self) -> None:
        for name in (
            "input_height",
            "input_width",
            "output_height",
            "output_width",
        ):
            _positive_integer(
                getattr(self, name),
                name=name,
            )

        horizontal_fov = _finite_float(
            self.horizontal_fov_rad,
            name="horizontal_fov_rad",
        )

        if not 0.0 < horizontal_fov < math.pi:
            raise ValueError(
                "horizontal_fov_rad must be within (0, pi)."
            )

        for name in (
            "k1",
            "k2",
            "p1",
            "p2",
            "k3",
        ):
            _finite_float(
                getattr(self, name),
                name=name,
            )

        for name in (
            "principal_x_fraction",
            "principal_y_fraction",
        ):
            value = _finite_float(
                getattr(self, name),
                name=name,
            )

            if not 0.0 <= value <= 1.0:
                raise ValueError(
                    f"{name} must be within [0, 1]."
                )

        focal_scale = _finite_float(
            self.distorted_focal_scale,
            name="distorted_focal_scale",
        )

        if focal_scale <= 0.0:
            raise ValueError(
                "distorted_focal_scale must be positive."
            )

        if not isinstance(
            self.crop_to_valid_region,
            bool,
        ):
            raise ValueError(
                "crop_to_valid_region must be a bool."
            )

        valid_margin = _finite_float(
            self.valid_source_margin_px,
            name="valid_source_margin_px",
        )

        if valid_margin < 0.0:
            raise ValueError(
                "valid_source_margin_px must be non-negative."
            )

        if (
            2.0 * valid_margin
            >= min(self.input_width, self.input_height) - 1
        ):
            raise ValueError(
                "valid_source_margin_px is too large for "
                "the configured input image."
            )

        fixed_crop = self.fixed_crop_xyxy

        if fixed_crop is not None:
            if (
                not isinstance(fixed_crop, tuple)
                or len(fixed_crop) != 4
                or any(
                    isinstance(value, bool)
                    or not isinstance(value, int)
                    for value in fixed_crop
                )
            ):
                raise ValueError(
                    "fixed_crop_xyxy must be an integer "
                    "(x0, y0, x1, y1) tuple."
                )

            x0, y0, x1, y1 = fixed_crop

            if (
                x0 < 0
                or y0 < 0
                or x1 > self.input_width
                or y1 > self.input_height
                or x1 <= x0
                or y1 <= y0
            ):
                raise ValueError(
                    "fixed_crop_xyxy must define a positive "
                    "crop inside the input image."
                )

            crop_width = x1 - x0
            crop_height = y1 - y0

            if (
                crop_width * self.output_height
                != crop_height * self.output_width
            ):
                raise ValueError(
                    "fixed_crop_xyxy aspect ratio must match "
                    "the configured output aspect ratio."
                )

    @property
    def input_shape(self) -> tuple[int, int, int]:
        """Expected raw RGB image shape."""

        return (
            self.input_height,
            self.input_width,
            3,
        )

    @property
    def output_shape(self) -> tuple[int, int, int]:
        """Policy RGB image shape."""

        return (
            self.output_height,
            self.output_width,
            3,
        )

    @property
    def distortion_coefficients(
        self,
    ) -> np.ndarray:
        """Return OpenCV Brown-Conrady coefficients."""

        return np.array(
            [
                self.k1,
                self.k2,
                self.p1,
                self.p2,
                self.k3,
            ],
            dtype=np.float64,
        )


def default_simulation_top_camera_processing_config(
) -> TopCameraProcessingConfig:
    """Return the provisional visual-match profile for simulation.

    These coefficients are visual tuning values, not calibration results.
    Replace them with measured real-camera intrinsics and distortion
    coefficients after formal camera calibration.
    """

    return TopCameraProcessingConfig(
        input_height=600,
        input_width=800,
        output_height=480,
        output_width=640,
        horizontal_fov_rad=math.radians(100.0),
        k1=-0.226598,
        k2=0.039593,
        p1=0.0,
        p2=0.0,
        k3=0.0,
        principal_x_fraction=0.4801,
        principal_y_fraction=0.4979,
        distorted_focal_scale=1.40,
        crop_to_valid_region=False,
        fixed_crop_xyxy=(10, 18, 758, 579),
    )


class TopCameraImageProcessor:
    """Apply fixed-camera distortion and policy resizing."""

    def __init__(
        self,
        config: TopCameraProcessingConfig | None = None,
    ) -> None:
        self.config = (
            TopCameraProcessingConfig()
            if config is None
            else config
        )
        self._cv2 = _load_cv2()

        self._source_camera_matrix = (
            self._build_source_camera_matrix()
        )
        self._distorted_camera_matrix = (
            self._build_distorted_camera_matrix()
        )
        self._distortion_coefficients = (
            self.config.distortion_coefficients
        )

        self._identity_mapping = bool(
            np.all(self._distortion_coefficients == 0.0)
            and self.config.distorted_focal_scale == 1.0
        )

        self._map_x: np.ndarray | None = None
        self._map_y: np.ndarray | None = None
        self._crop_bounds_xyxy = (
            0,
            0,
            self.config.input_width,
            self.config.input_height,
        )

        if not self._identity_mapping:
            self._map_x, self._map_y = (
                self._build_inverse_distortion_maps()
            )

        if self.config.fixed_crop_xyxy is not None:
            self._crop_bounds_xyxy = (
                self.config.fixed_crop_xyxy
            )
        elif (
            not self._identity_mapping
            and self.config.crop_to_valid_region
        ):
            self._crop_bounds_xyxy = (
                self._build_valid_crop_bounds()
            )

    def _build_source_camera_matrix(
        self,
    ) -> np.ndarray:
        width = self.config.input_width
        height = self.config.input_height

        focal_length = (
            0.5
            * width
            / math.tan(
                0.5 * self.config.horizontal_fov_rad
            )
        )

        principal_x = (
            (width - 1)
            * self.config.principal_x_fraction
        )
        principal_y = (
            (height - 1)
            * self.config.principal_y_fraction
        )

        return np.array(
            [
                [focal_length, 0.0, principal_x],
                [0.0, focal_length, principal_y],
                [0.0, 0.0, 1.0],
            ],
            dtype=np.float64,
        )

    def _build_distorted_camera_matrix(
        self,
    ) -> np.ndarray:
        matrix = self._source_camera_matrix.copy()
        scale = self.config.distorted_focal_scale

        matrix[0, 0] *= scale
        matrix[1, 1] *= scale

        return matrix

    def _build_inverse_distortion_maps(
        self,
    ) -> tuple[np.ndarray, np.ndarray]:
        """Map each distorted destination pixel to the pinhole source."""

        grid_y, grid_x = np.indices(
            (
                self.config.input_height,
                self.config.input_width,
            ),
            dtype=np.float32,
        )

        distorted_points = np.stack(
            (
                grid_x.reshape(-1),
                grid_y.reshape(-1),
            ),
            axis=-1,
        ).reshape(-1, 1, 2)

        source_points = self._cv2.undistortPoints(
            distorted_points,
            self._distorted_camera_matrix,
            self._distortion_coefficients,
            P=self._source_camera_matrix,
        )

        map_x = source_points[:, 0, 0].reshape(
            self.config.input_height,
            self.config.input_width,
        )
        map_y = source_points[:, 0, 1].reshape(
            self.config.input_height,
            self.config.input_width,
        )

        return (
            np.ascontiguousarray(
                map_x,
                dtype=np.float32,
            ),
            np.ascontiguousarray(
                map_y,
                dtype=np.float32,
            ),
        )

    @property
    def crop_bounds_xyxy(
        self,
    ) -> tuple[int, int, int, int]:
        """Return the automatically selected crop as x0, y0, x1, y1."""

        return self._crop_bounds_xyxy

    @property
    def crop_shape(self) -> tuple[int, int]:
        """Return crop height and width before policy resizing."""

        x0, y0, x1, y1 = self._crop_bounds_xyxy
        return y1 - y0, x1 - x0

    def _build_valid_crop_bounds(
        self,
    ) -> tuple[int, int, int, int]:
        """Find the largest centered output-aspect crop with no border."""

        assert self._map_x is not None
        assert self._map_y is not None

        width = self.config.input_width
        height = self.config.input_height
        margin = self.config.valid_source_margin_px

        valid = (
            (self._map_x >= margin)
            & (
                self._map_x
                <= float(width - 1) - margin
            )
            & (self._map_y >= margin)
            & (
                self._map_y
                <= float(height - 1) - margin
            )
        )

        # Integral image of invalid pixels permits O(1) rectangle checks.
        invalid = np.logical_not(valid).astype(
            np.int32
        )
        invalid_integral = np.pad(
            invalid,
            ((1, 0), (1, 0)),
            mode="constant",
        ).cumsum(axis=0).cumsum(axis=1)

        ratio_divisor = math.gcd(
            self.config.output_width,
            self.config.output_height,
        )
        ratio_width = (
            self.config.output_width
            // ratio_divisor
        )
        ratio_height = (
            self.config.output_height
            // ratio_divisor
        )

        maximum_scale = min(
            width // ratio_width,
            height // ratio_height,
        )

        center_x = (
            (width - 1)
            * self.config.principal_x_fraction
        )
        center_y = (
            (height - 1)
            * self.config.principal_y_fraction
        )

        for scale in range(
            maximum_scale,
            0,
            -1,
        ):
            crop_width = ratio_width * scale
            crop_height = ratio_height * scale

            x0 = int(
                round(
                    center_x
                    - 0.5 * (crop_width - 1)
                )
            )
            y0 = int(
                round(
                    center_y
                    - 0.5 * (crop_height - 1)
                )
            )
            x1 = x0 + crop_width
            y1 = y0 + crop_height

            if (
                x0 < 0
                or y0 < 0
                or x1 > width
                or y1 > height
            ):
                continue

            invalid_count = int(
                invalid_integral[y1, x1]
                - invalid_integral[y0, x1]
                - invalid_integral[y1, x0]
                + invalid_integral[y0, x0]
            )

            if invalid_count == 0:
                return x0, y0, x1, y1

        raise RuntimeError(
            "Could not find a valid top-camera crop "
            "without remapping borders."
        )

    def process(
        self,
        image: np.ndarray,
    ) -> np.ndarray:
        """Return a distorted and resized RGB uint8 policy image."""

        image_array = np.asarray(image)

        if image_array.dtype != np.uint8:
            raise ValueError(
                "Top-camera image must have dtype uint8."
            )

        if image_array.shape != self.config.input_shape:
            raise ValueError(
                "Top-camera image must have shape "
                f"{self.config.input_shape}, received "
                f"{image_array.shape}."
            )

        source = np.ascontiguousarray(image_array)

        if self._identity_mapping:
            transformed = source
        else:
            assert self._map_x is not None
            assert self._map_y is not None

            transformed = self._cv2.remap(
                source,
                self._map_x,
                self._map_y,
                interpolation=self._cv2.INTER_LINEAR,
                borderMode=self._cv2.BORDER_CONSTANT,
                borderValue=(0, 0, 0),
            )

        x0, y0, x1, y1 = (
            self._crop_bounds_xyxy
        )
        transformed = transformed[
            y0:y1,
            x0:x1,
        ]

        if (
            self.config.output_width
            == transformed.shape[1]
            and self.config.output_height
            == transformed.shape[0]
        ):
            result = transformed.copy()
        else:
            result = self._cv2.resize(
                transformed,
                (
                    self.config.output_width,
                    self.config.output_height,
                ),
                interpolation=self._cv2.INTER_AREA,
            )

        output = np.ascontiguousarray(
            result,
            dtype=np.uint8,
        )
        output.setflags(write=False)
        return output
